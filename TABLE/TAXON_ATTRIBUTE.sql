COMMENT ON COLUMN "TAXON_ATTRIBUTE"."ATTRIBUTE_VALUE" IS 'The value of the attribue';
COMMENT ON COLUMN "TAXON_ATTRIBUTE"."TAXON_NAME_ID" IS 'Taxonomy record to which this attribute applies.';
COMMENT ON COLUMN "TAXON_ATTRIBUTE"."CREATED_AGENT_ID" IS 'The agent who created this taxon attribute record.';
COMMENT ON COLUMN "TAXON_ATTRIBUTE"."CREATED_TIMESTAMP" IS 'The date this record was created.';
COMMENT ON COLUMN "TAXON_ATTRIBUTE"."LAST_MODIFIED" IS 'The date this record was last modified.';
