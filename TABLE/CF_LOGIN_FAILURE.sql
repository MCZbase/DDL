
  CREATE TABLE "CF_LOGIN_FAILURE" 
   (	"CF_LOGIN_FAILURE_ID" NUMBER GENERATED ALWAYS AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"LOCK_KIND" VARCHAR2(10) NOT NULL ENABLE, 
	"LOCK_KEY" VARCHAR2(255) NOT NULL ENABLE, 
	"FAILURES" NUMBER(6,0) DEFAULT 0 NOT NULL ENABLE, 
	"WINDOW_START" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	"LOCKED_UNTIL" DATE, 
	 CONSTRAINT "CF_LOGIN_FAILURE_KIND_CK" CHECK ("LOCK_KIND" IN ('username', 'address')) ENABLE, 
	 CONSTRAINT "CF_LOGIN_FAILURE_FAILURES_CK" CHECK ("FAILURES" >= 0) ENABLE, 
	 CONSTRAINT "CF_LOGIN_FAILURE_PK" PRIMARY KEY ("CF_LOGIN_FAILURE_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CF_LOGIN_FAILURE_U1" UNIQUE ("LOCK_KIND", "LOCK_KEY")
  USING INDEX  ENABLE
   ) ;
COMMENT ON TABLE "CF_LOGIN_FAILURE" IS 'Failed MCZbase logins and timed login locks, by username and by client address. Written by shared/component/loginThrottle.cfc; cleared daily by the CF_LOGIN_FAILURE_CLEANUP job.';
COMMENT ON COLUMN "CF_LOGIN_FAILURE"."CF_LOGIN_FAILURE_ID" IS 'surrogate numeric primary key';
COMMENT ON COLUMN "CF_LOGIN_FAILURE"."LOCK_KIND" IS 'username or address';
COMMENT ON COLUMN "CF_LOGIN_FAILURE"."LOCK_KEY" IS 'The username typed, in lower case, whether or not such a user exists; or the client address.';
COMMENT ON COLUMN "CF_LOGIN_FAILURE"."FAILURES" IS 'Failed logins since WINDOW_START.';
COMMENT ON COLUMN "CF_LOGIN_FAILURE"."WINDOW_START" IS 'Start of the period over which FAILURES are counted.';
COMMENT ON COLUMN "CF_LOGIN_FAILURE"."LOCKED_UNTIL" IS 'Logins for this username or address are refused until this time; null if not locked.';
